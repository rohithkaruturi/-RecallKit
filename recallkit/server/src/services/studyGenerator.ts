import { v4 as uuidv4 } from 'uuid';
import type { GenerateRequest, StudySet, RawStudySet } from '../../../shared/types';
import { buildStudyPrompt, buildRepairPrompt } from '../prompts/studyPrompt';
import { generateContentWithGroq } from './groqService';
import { parseJsonResponse } from './responseParser';
import { validateStudyResponse } from './responseValidator';
import { AppError } from '../utils/AppError';

export interface GenerationTrace {
  attempts: number;
  repaired: boolean;
  errors?: string[];
}

/**
 * Main AI Generation & Validation Pipeline.
 * Orchestrates prompt building, LLM generation, JSON parsing, Zod validation,
 * automatic single-attempt repair loop, and ID enrichment.
 */
export async function generateStudySet(
  request: GenerateRequest,
  onTrace?: (trace: GenerationTrace) => void
): Promise<StudySet> {
  const { notes, mode, difficulty } = request;

  // 1. Build initial prompt
  const initialPrompt = buildStudyPrompt(notes, mode, difficulty);

  // 2. First generation attempt
  let rawResponse = await generateContentWithGroq(initialPrompt);
  let parseResult = parseJsonResponse(rawResponse);

  // 3. Initial validation check
  let validationResult = parseResult.success
    ? validateStudyResponse(parseResult.data, mode, notes)
    : { success: false, errors: [parseResult.error] };

  let repaired = false;

  // 4. Automated single-attempt repair loop
  if (!validationResult.success) {
    const errorDetails = validationResult.errors;

    // Build repair prompt sending errors back to Groq
    const repairPrompt = buildRepairPrompt(initialPrompt, rawResponse, errorDetails);

    try {
      rawResponse = await generateContentWithGroq(repairPrompt);
      parseResult = parseJsonResponse(rawResponse);

      if (parseResult.success) {
        validationResult = validateStudyResponse(parseResult.data, mode, notes);
        repaired = validationResult.success;
      } else {
        validationResult = { success: false, errors: [`Repair parsing failed: ${parseResult.error}`] };
      }
    } catch (repairErr) {
      const msg = repairErr instanceof Error ? repairErr.message : String(repairErr);
      validationResult = { success: false, errors: [`Repair generation failed: ${msg}`] };
    }

    // If still invalid after 1 repair attempt, fail safely with controlled AppError
    if (!validationResult.success || !validationResult.data) {
      throw new AppError(
        'INVALID_AI_OUTPUT',
        `Unable to generate valid study material after repair attempt: ${validationResult.errors.join('; ')}`,
        true,
        502
      );
    }
  }

  if (onTrace) {
    onTrace({
      attempts: repaired ? 2 : 1,
      repaired,
      errors: validationResult.errors,
    });
  }

  // 5. Enrich validated data with application IDs
  return enrichWithApplicationIds(validationResult.data!);
}

/**
 * Enriches raw AI study set with unique application UUIDs and timestamps.
 * IDs are NEVER generated by the LLM.
 */
export function enrichWithApplicationIds(raw: RawStudySet): StudySet {
  return {
    id: uuidv4(),
    title: raw.title.trim(),
    summary: raw.summary.trim(),
    flashcards: raw.flashcards.map((f) => ({
      id: uuidv4(),
      front: f.front.trim(),
      back: f.back.trim(),
      sourceExcerpt: f.sourceExcerpt.trim(),
    })),
    quiz: raw.quiz.map((q) => ({
      id: uuidv4(),
      question: q.question.trim(),
      options: q.options.map((opt) => ({
        id: opt.id.trim().toUpperCase(),
        text: opt.text.trim(),
      })),
      correctOptionId: q.correctOptionId.trim().toUpperCase(),
      explanation: q.explanation.trim(),
      sourceExcerpt: q.sourceExcerpt.trim(),
    })),
    createdAt: new Date().toISOString(),
  };
}
